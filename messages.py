def pick(lst: list[str]) -> str:
    return random.choice(lst)


def render_two_days_not_started(name: str, task: str, status: str) -> str:
    return pick(TWO_DAYS_NOT_STARTED).format(name=name, task=task, status=status)


def render_one_day_left(name: str, task: str, status: str) -> str:
    return pick(ONE_DAY_LEFT).format(name=name, task=task, status=status)


def render_reminder(name: str, task: str, days_overdue: int) -> str:
    if days_overdue <= 0:
        template = pick(DUE_TODAY)
    elif days_overdue <= 3:
        template = pick(OVERDUE_LIGHT)
    elif days_overdue <= 7:
        template = pick(OVERDUE_MEDIUM)
    else:
        template = pick(OVERDUE_HEAVY)
    return template.format(name=name, task=task, days=days_overdue)
